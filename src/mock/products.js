const UNISEX_SIZES = ["S", "M", "L", "XL", "XXL"];
const WOMEN_SIZES = ["XS", "S", "M", "L", "XL"];
const WAIST_SIZES = ["28", "30", "32", "34", "36"];

// Deterministic stock so the demo looks the same on every reload (includes 0s and low stock)
const STOCK_CYCLE = [12, 7, 0, 4, 9, 2, 15, 6, 3, 10, 8];

function buildVariants(sku, sizes, colors, seed, soldOut) {
  const out = [];
  sizes.forEach((size, i) =>
    colors.forEach((color, j) => {
      out.push({
        sku: `${sku}-${size.replace(/\s/g, "")}-${color.name.slice(0, 3).toUpperCase()}`,
        size,
        color: color.name,
        stock: soldOut
          ? 0
          : STOCK_CYCLE[(seed + i * 5 + j * 3) % STOCK_CYCLE.length],
      });
    }),
  );
  return out;
}

function make(id, o) {
  const slug = slugify(o.name);
  const sku = `TS-${String(id).padStart(3, "0")}`;
  const sizes = o.sizes || UNISEX_SIZES;
  const photos = PRODUCT_IMAGES[slug] || ["", "", ""];
  return {
    id,
    slug,
    sku,
    name: o.name,
    type: o.type,
    categories: o.categories,
    tags: o.tags || [],
    price: o.price,
    salePrice: o.salePrice ?? null,
    description: o.description,
    specs: [
      ["Fabric", o.fabric],
      ["Fit", o.fit],
      ["Care", o.care || "Machine wash cold, inside out. Do not tumble dry."],
      ["SKU", sku],
    ],
    colors: o.colors,
    sizes,
    variants: buildVariants(sku, sizes, o.colors, id, !!o.soldOut),
    images: photos.map((url, i) => ({ url, alt: `${o.name}, view ${i + 1}` })),
    isNew: !!o.isNew,
    isBestSeller: !!o.isBestSeller,
    isTrending: !!o.isTrending,
    popularity: o.popularity,
    rating: o.rating,
    reviewCount: o.reviewCount,
    createdAt: o.createdAt,
  };
}

